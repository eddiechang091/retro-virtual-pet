// Retro 1-bit Dot-Matrix Pixel Art Data for Tamagotchi Pet
// 1 = Dark LCD Pixel (#242926), 0 = LCD Background

export type PixelMatrix = number[][];

// Helper to convert ascii visual art to 0/1 matrix
export function parseAscii(art: string[]): PixelMatrix {
  return art.map(row => 
    row.trim().split('').map(char => (char === '#' || char === 'X' || char === '1' ? 1 : 0))
  );
}

